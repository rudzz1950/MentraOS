#!/usr/bin/env python3
"""
Generate the C header for ring and glasses firmware, and the TypeScript for the phone, from proto/ecosystem_events.v1.json. ANI-177.

The JSON is the contract; the header is generated from it and committed.
`--check` fails when the committed header no longer matches the JSON, the same
way check-proto-codegen.py guards the protobuf bindings: generated code that
drifts from its schema is how the original .proto had to be recovered by
decompiling.

Usage:
  python3 scripts/gen-ecosystem-c.py           # write proto/ecosystem_events.h
  python3 scripts/gen-ecosystem-c.py --check   # exit 1 if it is out of date
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "proto" / "ecosystem_events.v1.json"
OUT = ROOT / "proto" / "ecosystem_events.h"
TS_OUT = ROOT / "miniapps" / "assistant" / "src" / "bus" / "ecosystem.generated.ts"


def render_ts(c: dict) -> str:
    body = json.dumps(c, indent=2, ensure_ascii=False)
    return (
        "// GENERATED by scripts/gen-ecosystem-c.py from proto/ecosystem_events.v1.json. Do not edit.\n"
        f"export const ECOSYSTEM_CONTRACT = {body} as const\n"
    )


def ident(s: str) -> str:
    return re.sub(r"[^A-Z0-9]", "_", s.upper())


def render(c: dict) -> str:
    v = c["version"]
    lines = [
        "/* GENERATED by scripts/gen-ecosystem-c.py from proto/ecosystem_events.v1.json. Do not edit. */",
        "#pragma once",
        "#include <stdint.h>",
        "",
        f"#define ECO_CONTRACT_VERSION {v}u",
        "",
        "typedef enum {",
    ]
    for i, e in enumerate(c["events"]):
        lines.append(f"\tECO_EVT_{ident(e['type'])} = {i + 1},")
    lines += ["} eco_event_type_t;", "", "typedef enum {"]
    for i, k in enumerate(["intent", "response", "telemetry"]):
        lines.append(f"\tECO_CLASS_{ident(k)} = {i},")
    lines += ["} eco_event_class_t;", "", "typedef enum {"]
    for i, r in enumerate(c["nack_reasons"]):
        lines.append(f"\tECO_NACK_{ident(r)} = {i + 1},")
    lines += ["} eco_nack_reason_t;", ""]
    for e in c["events"]:
        for name, f in e["fields"].items():
            vals = f.get("enum") or (c[f["enum_ref"]] if "enum_ref" in f else None)
            if vals and "enum_ref" not in f:
                lines.append("typedef enum {")
                for i, val in enumerate(vals):
                    lines.append(f"\tECO_{ident(e['type'])}_{ident(name)}_{ident(val)} = {i + 1},")
                lines.append(f"}} eco_{ident(e['type']).lower()}_{name}_t;")
                lines.append("")
    lines.append("/* Time-to-live per event type, milliseconds. */")
    lines.append("static const uint32_t ECO_TTL_MS[] = {")
    lines.append("\t0,")
    for e in c["events"]:
        lines.append(f"\t{e['ttl_ms']}u, /* {e['type']} */")
    lines.append("};")
    lines.append("")
    lines.append("static const eco_event_class_t ECO_CLASS_OF[] = {")
    lines.append("\tECO_CLASS_TELEMETRY,")
    for e in c["events"]:
        lines.append(f"\tECO_CLASS_{ident(e['class'])}, /* {e['type']} */")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    contract = json.loads(SRC.read_text(encoding="utf-8"))
    outputs = {OUT: render(contract), TS_OUT: render_ts(contract)}
    if "--check" in argv:
        stale = [p for p, text in outputs.items() if (p.read_text(encoding="utf-8") if p.exists() else "") != text]
        if stale:
            for p in stale:
                print(f"{p.relative_to(ROOT)} is out of date with ecosystem_events.v1.json; run scripts/gen-ecosystem-c.py")
            return 1
        print("generated C and TypeScript match the contract")
        return 0
    for p, text in outputs.items():
        p.write_text(text, encoding="utf-8")
        print(f"wrote {p.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
